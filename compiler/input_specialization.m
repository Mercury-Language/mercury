input_specialize_in_module(!ModuleInfo, !Specs) :-
    module_info_get_input_spec_table(!.ModuleInfo, InputSpecTable),
    module_info_get_valid_pred_ids(!.ModuleInfo, PredIds),
    list.foldl3(maybe_input_specialize_in_pred(InputSpecTable), PredIds,
        [], SpecPredIds, !ModuleInfo, !Specs),
    module_info_get_pragma_exported_procs(!.ModuleInfo, ExportedProcCord0),
    ( if
        SpecPredIds = [_ | _],
        cord.is_non_empty(ExportedProcCord0)
    then
        set_tree234.list_to_set(SpecPredIds, SpecPredIdSet),
        cord.map_pred(
            update_exported_proc_id_if_needed(!.ModuleInfo, SpecPredIdSet),
            ExportedProcCord0, ExportedProcCord),
        module_info_set_pragma_exported_procs(ExportedProcCord, !ModuleInfo)
    else
        true
    ).

:- pred maybe_input_specialize_in_pred(input_spec_table::in, pred_id::in,
    list(pred_id)::in, list(pred_id)::out,
    module_info::in, module_info::out,
    list(diag_spec)::in, list(diag_spec)::out) is det.

maybe_input_specialize_in_pred(InputSpecTable, PredId,
        !SpecPredIds, !ModuleInfo, !Specs) :-
    module_info_pred_info(!.ModuleInfo, PredId, PredInfo0),
    pred_info_get_module_name(PredInfo0, ModuleName),
    ( if map.search(InputSpecTable, ModuleName, InModuleMap) then
        pred_info_get_origin(PredInfo0, Origin),
        (
            Origin = origin_user(UserMade),
            (
                UserMade = user_made_pred(_, _, _),
                input_specialize_in_pred_if_possible(!.ModuleInfo, InModuleMap,
                    PredInfo0, MaybeNewPredInfo, !Specs),
                (
                    MaybeNewPredInfo = no
                ;
                    MaybeNewPredInfo = yes(NewPredInfo),
                    !:SpecPredIds = [PredId | !.SpecPredIds],
                    module_info_set_pred_info(PredId, NewPredInfo, !ModuleInfo)
                )
            ;
                ( UserMade = user_made_lambda(_, _, _)
                ; UserMade = user_made_class_method(_, _)
                ; UserMade = user_made_instance_method(_, _)
                ; UserMade = user_made_assertion(_, _, _)
                )
                % It would make sense to specialize lambda expressions,
                % but they will exist in the form of separate predicates
                % only after the frontend pass.
                %
                % For class and instance methods, altering their signature
                % would be a bug.
                %
                % For assertions, specializations of any kind are irrelevant.
            )
        ;
            ( Origin = origin_compiler(_)
            ; Origin = origin_pred_transform(_, _, _)
            ; Origin = origin_proc_transform(_, _, _, _)
            )
            % Do not specialize either unify/compare/index predicates,
            % or predicates implementing initialise, finalise, mutable
            % and solver type declarations. The other kinds of compiler-made
            % predicates, and all transformed predicates, can only be created
            % by compiler passes that execute after the frontend.
        )
    else
        true
    ).

:- pred input_specialize_in_pred_if_possible(module_info::in,
    input_spec_in_module_map::in, pred_info::in, maybe(pred_info)::out,
    list(diag_spec)::in, list(diag_spec)::out) is det.

input_specialize_in_pred_if_possible(ModuleInfo, InModuleMap,
        PredInfo0, MaybeNewPredInfo, !Specs) :-
    pred_info_get_arg_types(PredInfo0, ArgTypes),
    find_args_to_specialize(InModuleMap, 1, ArgTypes, ArgsToSpec),
    (
        ArgsToSpec = [],
        MaybeNewPredInfo = no
    ;
        ArgsToSpec = [HeadArgToSpec | TailArgsToSpec],
        report_any_incompatibilities(PredInfo0, PredSpecs),
        (
            PredSpecs = [],
            input_specialize_in_pred(ModuleInfo, HeadArgToSpec, TailArgsToSpec,
                PredInfo0, NewPredInfo),
            MaybeNewPredInfo = yes(NewPredInfo)
        ;
            PredSpecs = [_ | _],
            !:Specs = PredSpecs ++ !.Specs,
            MaybeNewPredInfo = no
        )
    ).

:- type arg_to_specialize
    --->    arg_to_specialize(int, input_spec_info).
            % The argument number, and how to specialize it.

:- pred find_args_to_specialize(input_spec_in_module_map::in,
    int::in, list(mer_type)::in, list(arg_to_specialize)::out) is det.

find_args_to_specialize(_, _, [], []).
find_args_to_specialize(InModuleMap, ArgNum, [ArgType | ArgTypes],
        ArgsToSpec) :-
    find_args_to_specialize(InModuleMap, ArgNum + 1, ArgTypes,
        ArgsToSpecTail),
    % This search works only if the types in input_spec pragmas are ground.
    % At the moment, add_pragma_decl.m does require them to be ground.
    ( if map.search(InModuleMap, ArgType, InputSpecInfo) then
        ArgToSpec = arg_to_specialize(ArgNum, InputSpecInfo),
        ArgsToSpec = [ArgToSpec | ArgsToSpecTail]
    else
        ArgsToSpec = ArgsToSpecTail
    ).

