% File: input_specialization.m.
% Author: zs.
%
% This module implements input specialization pragmas.
%
% Given
%
%   :- pragma input_spec(<type>, <replace_or_add>,
%       [inst_name1, ..., inst_nameN]).
%
% in either module M's .m file or its .int file,
%
% - it looks for predicates and/or functions in module M
%   one or more of whose argument types are <type>,
%
% - for each argument position for which that is tue,
%   it looks for modes that specify "in" in that argument position,
%
% - creates copies of those modes that replace "in" with "in(inst_nameI")
%   for all I in 1..N;
%
% - and either replaces the original mode with its modified copies
%   (if <replace_or_add> is replace_in_mode, or adds the modified copies
%   before the original mode (if <replace_or_add> is add_to_in_mode).
%
% If a predicate or function has more than one mode that specifies the "in"
% mode for argument to be input specialized, the same addition or replacement
% will happen for all of them.
%
% If a predicate or function has more than argument that should be input
% specialized, then the input to the process of specializing the Nth such
% argument is the mode list generated by specializing the previous N-1
% arguments. In other words, the final result will be a mode list that
% could be called a "cross product" of all the input specializations.
%
%---------------------------------------------------------------------------%
%
% This program transformation can change the proc_id of a procedure
% in a predicate or function. This means that it can potentially affect
% the operation of all Mercury program constructs that refer to proc_ids.
% These constructs are all pragmas.
%
% The following lists the pragmas that can refer to specific procedures
% (as opposed to whole predicates and/or functions), and how we handle them.
% A common theme is that the code that add the pragma to the HLDS
% puts information about it into a field of the proc_info, and that
% this module both preserves that field in the original procedure and
% copies it to any input-specialized procedures.
%
% termination
% termination2
% require_tail_rec
%   The compiler records these pragmas in the termination_info,
%   termination2_info, and require_tailrec_info fields of the proc_info
%   respectively. The parts of the passes implementing these pragmas
%   that generate the diagnostics that they call for can include proc_ids
%   (mode numbers) in those diagnostics, but they will map the then-actual
%   proc_ids back to their original proc_ids using the maybe_input_spec field,
%   which is set by code in this module. This mapping back is done by
%   describe_one_proc_name and its variants, and by its subcontractor
%   original_proc_id, in hlds_error_util.
%
% obsolete_proc
%   The compiler records this pragma in the obsolete_in_favour_of field
%   of the proc_info. simplify_goal_call.m, which implements the pragma,
%   looks only at this field, so it gets the "should this call get an
%   obsolete proc warning" test right using its existing code. And the code
%   generating the warning did not need any changes either, because its text
%   identifies the obsolete procedure not by giving its proc_id, but by
%   listing its argument modes.
%
% foreign_proc
%   The compiler records this pragma BY PRED_ID AND PROC_ID in the
%   pragma_exported_procs field of the module_info. If the pred_id
%   in such as record identifies a predicate that we input specialize,
%   then update_exported_proc_id_if_needed below will update the proc_id.
%
% tabled
%   The compiler generates target language variables and auxiliary predicates
%   whose names include the proc_id when it adds tabled pragmas to the HLDS.
%   Since input specialization can change these proc_ids, it is not compatible
%   with tabling. This is why if a predicate that *could* be input specialized
%   has one or more tabled procedures, we generate an error message, and
%   do not perform the input specialization.
%
%   (We do this even if the predicate's tabled procedures would NOT have
%   their proc_ids changed by input specialization. The reason for this
%   decision is that this is a fragile state of affairs, subject to change
%   e.g. by the addition of new modes, and it is better for programmers
%   to learn about this incompatibility before they start relying on
%   something that is liable to break later.)
%
%   There is one form of tabling, I/O tabling, that is implemented
%   entirely by table_gen.m, which runs much later than input specialization.
%   It applies only to predicates that do NOT have a tabled pragma,
%   so their implementations do not involve any variable or procedure names
%   that were decided at the add-pragma-to-the-HLDS time. Their implementation
%   works with the current proc_ids, and should work whether those proc_ids
%   were updated by input specialization or not. In some cases, we can
%   generate diagnostics for such predicates, and these diagnostics do
%   include proc_ids, but describe_one_proc_name maps them back to their
%   originals.
%
% structure_sharing
% structure_reuse
%   Both structure_sharing and structure_reuse pragmas can contain
%   structure_sharing_domains, which contain proc_ids. For pragmas read in
%   from other modules' .opt and/or .trans_opt files, we handle this
%   the same way we handle the interaction with tabling: if a predicate
%   that *could* be input specialized has one or more procedures for which
%   we have read sharing and/or reuse pragmas, we generate an error message,
%   and do not perform the input specialization.
%
%   When creating .opt and/or .trans_opt files, we do not output either
%   structure_sharing and structure_reuse pragmas for procedures that
%   are either logically deleted by input specialization (since they are
%   not supposed to be referred to at all), or are themselves the
%   specialized procedures created by input specialization (since we
%   don't yet know whether we want to export those procedures outside
%   their defining module, and no pragma in a .opt/.trans_opt file
%   should refer to a procedure that its reader may have no knowledge of).
%
% exceptions
% trailing
% mm_tabling
%   The compiler records these pragmas in the exception_info, trailing_info,
%   and mm_tabling_info fields of the proc_info respectively. When input
%   specialization specializes a procedure, these fields get copied as well,
%   and since specialization leaves the body goal of the procedure unchanged,
%   the analysis results they contain remain valid.
%
%   When intermodule optimization writes out these pragmas, we have handle
%   two issues. First as with the structure_sharing and structure_reuse
%   pragmas, we do not write out these pragmas for either procedures
%   logically deleted by input specialization, nor for the new specialized
%   procedures created by it. As for the procedures that do not fall into
%   either of those categories, the second issue is that their procedure number
%   may have been changed by input specialization. We therefore map
%   their procedure ids back to the original.
%
% unused_args
%   We handle writing out unused_args pragmas to .opt/.trans_opt files
%   the same say we handle writing exceptions, trailing, and mm_tabling
%   pragmas, and for the same reason.
%
%   For reading them in, we do not have to do anything special, because
%   while add the contents of each unused_args pragma we read in to a
%   table in the module_info, we do not actually DO anything with the
%   contents of the table :-)
%
% type_spec
%   We do not yet have code to handle these pragmas correctly.
%
%---------------------------------------------------------------------------%

